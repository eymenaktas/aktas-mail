/** `mail.github.com` -> `github.com`; en uzun eşleşmeden başlar. */
function markaBul(domain: string): Marka | null {
  const d = domain.toLowerCase();
  if (MARKALAR[d]) return MARKALAR[d]!;
  for (const anahtar of Object.keys(MARKALAR)) {
    if (d.endsWith(`.${anahtar}`)) return MARKALAR[anahtar]!;
  }
  return null;
}

/**
 * Domain için gömülü marka logosu (data URI) — yoksa null.
 *
 * ÇAĞIRAN TARAF SORUMLU: yalnızca domain doğrulanmışsa kullan.
 */
export function markaLogosu(domain: string): string | null {
  const m = markaBul(domain);
  if (!m) return null;
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="64" height="64">` +
    `<rect width="24" height="24" rx="5" fill="${m.renk}"/>` +
    `<g transform="translate(3.6,3.6) scale(0.7)">` +
    `<path fill="${m.glif ?? "#ffffff"}" d="${m.yol}"/></g></svg>`;
  return `data:image/svg+xml;base64,${Buffer.from(svg, "utf8").toString("base64")}`;
}

